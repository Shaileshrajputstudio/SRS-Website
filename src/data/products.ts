export type ProductCategory = (typeof productCategories)[number];

export type Product = {
  slug: string;
  displayName: string; // stylized, e.g. "MAR:GA"
  romanized: string; // e.g. "MAR:GA"
  series: string; // e.g. "Parth:Sarathi"
  category: ProductCategory;
  placeholder: boolean;
  about: string[]; // paragraphs
  closing: string[]; // italicized closing lines
  details: {
    productCode: string;
    material: string;
    dimensions: { height: string; width: string; depth: string };
    weight: string;
    leadTime: string;
  };
  images: string[];
};

function categorySlug(category: ProductCategory) {
  return category.toLowerCase().replace(/[^a-z0-9]+/g, "-");
}

function placeholderProduct(category: ProductCategory, index: number): Product {
  const slug = `${categorySlug(category)}-${index}`;
  return {
    slug,
    displayName: "Coming Soon",
    romanized: category,
    series: "—",
    category,
    placeholder: true,
    about: [
      `A product from the studio's ${category} range. Photography and the full story for this product are being prepared.`,
    ],
    closing: [],
    details: {
      productCode: "—",
      material: "—",
      dimensions: { height: "—", width: "—", depth: "—" },
      weight: "—",
      leadTime: "Enquire for availability.",
    },
    images: [`/images/products/placeholder/${categorySlug(category)}-${index}.svg`],
  };
}

