// Individual products — one level below Collections. Each product belongs
// to a named "series" (e.g. Parth:Sarathi), which is a different grouping
// than the six elemental Collections (Bhumi/Jal/Agni/Vayu/Vyom/Dhatu) built
// in src/data/collections.ts. How series and collections relate to each
// other is not yet resolved — flagged for the studio to confirm. Real data
// so far comes from product info shared directly (name, series, about copy,
// spec sheet); carousel photography is still placeholder.
//
// Category browsing (src/app/products/page.tsx) is a second, parallel
// discovery path alongside Collections — browse by product type (Wall
// Sconces, Floor Lamps, ...) instead of by elemental collection. Only
// MAR:GA is real; every other entry is a clearly-labeled placeholder
// (placeholder: true) standing in until the studio shares real product
// photography and names for that category.

